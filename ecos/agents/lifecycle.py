    RECEIVED = "RECEIVED"
    DECOMPOSED = "DECOMPOSED"
    ASSIGNED = "ASSIGNED"
    EXECUTING = "EXECUTING"
    COLLECTING = "COLLECTING"
    VERIFYING = "VERIFYING"
    REPLAN = "REPLAN"
    FINAL = "FINAL"
